"""# PART 9 — Build MULTI-SOURCE BFS ON STOP GRAPH"""

def multi_source_bfs(anchors: list[str], max_hops: int | None = None) -> dict:
    """
    Returns dict: stop_id -> min hop distance to ANY anchor in anchors.
    """
    dist = {}
    q = deque()

    # initialize all anchors at hop 0
    for a in anchors:
        a = str(a)
        dist[a] = 0
        q.append(a)

    while q:
        cur = q.popleft()
        d = dist[cur]
        if max_hops is not None and d >= max_hops:
            continue

        for nb in neighbors_all.get(cur, []):
            if nb not in dist:
                dist[nb] = d + 1
                q.append(nb)

    return dist

"""# PART 10 — Build event exposure sets (treated/control by hop, mode-aware)

## Decide hop threshold per event based on anchor mode
**We infer anchor mode from hubs.mode. Then choose hop depth from hops_by_mode.**
**solves your concern that “bus hops ≠ subway hops” in physical distance.**
"""

# ===== REPLACE CELL 42 =====
# Use hops_by_mode to create event-specific treated/control hop thresholds (Option 1)

stopid_to_route_types = stops2.set_index("stop_id")["route_types"].to_dict()

RT_TO_MODE = {0: "streetcar", 1: "subway", 3: "bus"}

def event_anchor_modes(anchor_stops):
    modes = set()
    for s in anchor_stops:
        rts = stopid_to_route_types.get(str(s), [])
        if isinstance(rts, list):
            for rt in rts:
                if rt in RT_TO_MODE:
                    modes.add(RT_TO_MODE[rt])
    # fallback if we failed to detect anything
    if len(modes) == 0:
        modes.add("bus")
    return sorted(modes)

def choose_event_hops(anchor_stops):
    modes = event_anchor_modes(anchor_stops)
    # Convert TARGET_DIST_M into hops per mode; fallback if missing
    mode_hops = [hops_by_mode.get(m, None) for m in modes]
    mode_hops = [h for h in mode_hops if h is not None]
    if len(mode_hops) == 0:
        # reasonable fallback
        treated = 6
    else:
        # safest: cover the largest hop-needed mode so treated region reaches ~TARGET_DIST_M
        treated = int(max(mode_hops))

    # define a control ring relative to treated (keeps logic consistent across events)
    control_min = treated + 4
    control_max = treated + 12

    return treated, control_min, control_max, modes

