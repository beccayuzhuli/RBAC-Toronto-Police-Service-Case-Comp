# ---------- 4) Bootstrap confidence intervals by resampling events ----------
def bootstrap_diff_curves(df_in: pd.DataFrame, bins: list, B: int = 300, seed: int = 42):
    rng = np.random.default_rng(seed)
    event_ids = df_in["event_id"].unique()
    rel_hours = np.sort(df_in["rel_hour"].unique())

    boot_store = {b: [] for b in bins}

    # Pre-slice by event to make bootstrapping faster
    by_event = {eid: g for eid, g in df_in.groupby("event_id")}

    for _ in range(B):
        sample_eids = rng.choice(event_ids, size=len(event_ids), replace=True)
        # concatenate sampled events (fast-ish)
        tmp = pd.concat([by_event[eid] for eid in sample_eids], ignore_index=True)

        m = (
            tmp.groupby(["rel_hour", "bin"], as_index=False)["rate"]
               .mean()
               .pivot(index="rel_hour", columns="bin", values="rate")
               .reindex(rel_hours)
        )

        # If some bins missing at some rel_hours, fill with 0 (conservative with sparse data)
        m = m.fillna(0.0)

        for b in bins:
            boot_store[b].append((m[b] - m["control_ring"]).to_numpy())

    # Convert to arrays: shape (B, T)
    out = {}
    for b in bins:
        arr = np.vstack(boot_store[b])
        out[b] = {
            "rel_hour": rel_hours,
            "mean": arr.mean(axis=0),
            "lo": np.quantile(arr, 0.025, axis=0),
            "hi": np.quantile(arr, 0.975, axis=0),
        }
    return out

