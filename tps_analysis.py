def haversine_m(lat1, lon1, lat2, lon2):
    R = 6371000.0
    lat1 = np.radians(lat1); lon1 = np.radians(lon1)
    lat2 = np.radians(lat2); lon2 = np.radians(lon2)
    dlat = lat2 - lat1
    dlon = lon2 - lon1
    a = np.sin(dlat/2)**2 + np.cos(lat1)*np.cos(lat2)*np.sin(dlon/2)**2
    c = 2*np.arcsin(np.sqrt(a))
    return R*c

def toronto_like_latlon(lat_s, lon_s):
    """
    Heuristic: Toronto area ~ lat 43-44, lon -80 to -78
    Returns True if medians look correct.
    """
    lat_med = np.nanmedian(lat_s)
    lon_med = np.nanmedian(lon_s)
    return (43.0 <= lat_med <= 44.5) and (-80.5 <= lon_med <= -78.0)

def autoswap_latlon(df, lat_col, lon_col, out_lat="lat", out_lon="lon"):
    """
    Creates numeric out_lat/out_lon from df[lat_col]/df[lon_col].
    Auto-swaps if they don't look like Toronto but swapped does.
    """
    lat = pd.to_numeric(df[lat_col], errors="coerce")
    lon = pd.to_numeric(df[lon_col], errors="coerce")
    if toronto_like_latlon(lat, lon):
        df[out_lat] = lat
        df[out_lon] = lon
        df["_latlon_swapped"] = False
        return df
    # try swap
    if toronto_like_latlon(lon, lat):
        df[out_lat] = lon
        df[out_lon] = lat
        df["_latlon_swapped"] = True
        return df
    # neither looks right; keep original
    df[out_lat] = lat
    df[out_lon] = lon
    df["_latlon_swapped"] = None
    return df

